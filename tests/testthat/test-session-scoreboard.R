test_that("session history includes the current finish once and retains all-time counts", {
  s <- table_session(new_holdem(seed=1))
  expect_equal(s$starting_stacks,c(100,100))
  expect_equal(table_bankrolls(s$game),c(100,100))
  s <- table_apply(s,list(action="fold"))
  expect_length(table_session_results(s),1)
  expect_equal(table_winners(s$game),2)
  next_state <- table_next(s)
  expect_equal(next_state$wins,c(0L,1L))
  expect_equal(next_state$completed_count,1)
  expect_length(table_session_results(next_state),1)
  expect_identical(next_state$starting_stacks,s$starting_stacks)
  skip_if_not_installed("shiny")
  html <- as.character(table_scoreboard(s))
  expect_false(grepl("hole|burned|controllers",html))
})
