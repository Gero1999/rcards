    session$setInputs(capture="1:1",decision=list(action="play",version=0))
    expect_equal(state()$actions,1)
    expect_length(selected(),0)
    expect_equal(length(state()$game$players[[1]]$hand),2)
  })
})

test_that("rendered cards escape labels and omit face data for backs", {
  skip_if_not_installed("shiny")
  card <- list(back=FALSE,value="<script>alert(1)</script>",suit="Hearts",symbol="H",label="<b>unsafe</b>")
  html <- as.character(table_card_tag(card,1,"hand",0))
  expect_false(grepl("<script>",html,fixed=TRUE))
  expect_match(html,"&lt;script&gt;",fixed=TRUE)
  hidden <- as.character(table_card_tag(list(back=TRUE),1,"seat_2",0))
  expect_false(grepl("unsafe|Hearts|alert",hidden))
})


