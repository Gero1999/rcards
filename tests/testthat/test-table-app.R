test_that("a capture choice for another hand card cannot resolve ambiguity", {
  skip_if_not_installed("shiny")
  g <- scopa_game(seed=1)
  g$table_cards <- list(card("5","Denari"),card("5","Coppe"))
  g$players[[1]]$hand <- list(card("5","Spade"),card("5","Bastoni"))
  initial <- table_session(g)
  shiny::testServer(table_app_server(initial,"en"),{
    session$flushReact()
    session$setInputs(card_pick=list(index=2L,zone="hand",version=0))
    session$setInputs(decision=list(action="play",version=0,capture="1:1"))
    expect_identical(state()$game,g)
    expect_match(state()$error,"capture option")
    session$setInputs(decision=list(action="play",version=0,capture="2:2"))
    expect_equal(state()$actions,1)
    expect_equal(state()$game$captured[[1]][[2]]$suit,"Coppe")
  })
})

test_that("split Blackjack hands progress and browser sessions are independent", {
  skip_if_not_installed("shiny")
  initial <- table_session(new_bj("8s 9h 8d 8c 2s 3d"))
  server <- table_app_server(initial,"en")
  shiny::testServer(server,{
    session$flushReact()
    session$setInputs(decision=list(action="split",version=0))
    expect_length(view()$own,2)
    expect_true(view()$own[[1]]$active)
    session$setInputs(decision=list(action="stand",version=1))
    expect_true(view()$own[[2]]$active)
    session$setInputs(decision=list(action="stand",version=2))
    expect_true(view()$hand_complete)
    expect_length(view()$result,2)
    expect_false(view()$center[[1]]$cards[[2]]$back)
    expect_false(view()$can_next)
  })
  shiny::testServer(server,{
    session$flushReact()
    expect_identical(state()$game,initial$game)
    expect_equal(state()$version,0)
    expect_true(view()$center[[1]]$cards[[2]]$back)
  })
})

test_that("Mus exchanges use selections and next hand retains match scores", {
  skip_if_not_installed("shiny")
  g <- new_mus(seed=4)
  for(i in 1:4) g <- mus_action(g,"mus")
  initial <- table_session(g)
  shiny::testServer(table_app_server(initial,"en"),{
    session$flushReact()
    session$setInputs(card_pick=list(index=1L,zone="hand",version=0))
    session$setInputs(decision=list(action="discard",version=0))
    expect_equal(state()$game$history[[5]]$cards,1L)
    expect_length(selected(),0)
    expect_length(state()$game$players[[1]]$hand,4)
  })
  g <- finish_mus_passing(new_mus(seed=5))
  initial <- table_session(g)
  shiny::testServer(table_app_server(initial,"en"),{
    session$flushReact()
    expect_true(view()$can_next)
    session$setInputs(table_continue=list(version=0))
    expect_equal(state()$game$hand_number,2)
    expect_equal(state()$game$scores,g$scores)
    expect_false(view()$hand_complete)
  })
})

