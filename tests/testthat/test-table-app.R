test_that("Shiny actions validate turns and preserve game state after invalid inputs", {
  skip_if_not_installed("shiny")
  initial <- table_session(new_holdem(seed=1))
  shiny::testServer(table_app_server(initial,"en"),{
    session$flushReact()
    session$setInputs(amount=0,decision=list(action="raise",version=0))
    expect_identical(state()$game,initial$game)
    expect_match(state()$error,"raise-to")
    session$setInputs(amount=4,decision=list(action="raise",version=0))
    expect_equal(state()$game$round_bets[1],4)
    expect_equal(state()$version,1)
    session$setInputs(decision=list(action="raise",version=0))
    expect_equal(state()$version,1)
    session$setInputs(language="it")
    expect_equal(view()$language,"it")
    expect_null(view()[["game"]])
  })
})

test_that("card selection is limited to the viewer and Scopa moves reach the engine", {
  skip_if_not_installed("shiny")
