test_that("Scopa radio labels distinguish equal ranks with public suit marks", {
  skip_if_not_installed("shiny")
  game <- scopa_game(seed = 1)
  game$table_cards <- list(card("1", "Denari"), card("1", "Bastoni"), card("4", "Coppe"))
  game$players[[1L]]$hand <- list(card("5", "Spade"), card("10", "Coppe"))
  view <- game_table_view(game)

  markup <- as.character(table_scopa_capture_picker(view, 1L, 4L))
  expect_match(markup, 'name="capture" value="4:1:1"', fixed = TRUE)
  expect_match(markup, 'name="capture" value="4:1:2"', fixed = TRUE)
  expect_match(markup, "rc-suit-coin", fixed = TRUE)
  expect_match(markup, "rc-suit-baton", fixed = TRUE)
  expect_match(markup, "Take Ace of Coins + 4 of Cups", fixed = TRUE)
  expect_match(markup, "Take Ace of Batons + 4 of Cups", fixed = TRUE)
  expect_false(grepl("checked", markup, fixed = TRUE))
  expect_false(grepl("checked", as.character(table_scopa_capture_picker(view, 1L, 4L, "4:2:1")), fixed = TRUE))
  expect_false(grepl("checked", as.character(table_scopa_capture_picker(view, 1L, 4L, "3:1:1")), fixed = TRUE))
  expect_match(as.character(table_scopa_capture_picker(view, 1L, 4L, "4:1:2")), 'value="4:1:2" checked', fixed = TRUE)

  passing <- as.character(table_scopa_capture_picker(view, 2L, 4L))
  expect_match(passing, 'value="4:2:1" checked', fixed = TRUE)
  expect_match(passing, "leave on table", fixed = TRUE)
  expect_null(table_scopa_capture_picker(view, integer(), 4L))
})
