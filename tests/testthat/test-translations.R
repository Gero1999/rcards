test_that("translation changes displays but preserves game identity", {
  c <- card("A","Spades",display="custom")
  es <- translate_card(c,"es")
  expect_equal(es$display,"As de Picas \u2660")
  expect_identical(es[c("value","suit","symbol")],c[c("value","suit","symbol")])
  expect_equal(translate_card(es,"en")$display,"Ace of Spades \u2660")
  expect_match(translate_card(card("11","Copas"),"en")$display,"Knight of Cups")
  expect_match(translate_card(card("11","Copas"),"es")$display,"Caballo de Copas")
  expect_error(translate_card(c,"fr"),"en and es")
})

test_that("deck translation preserves optional metadata, order and poker rankings", {
  d <- poker_pack()
  translated <- translate_deck(d,"es")
  expect_identical(poker_card_ids(translated),poker_card_ids(d))
  expect_equal(attr(translated,"language"),"es")
  expect_equal(poker_hand_points(as_card_list(d)[1:7]),poker_hand_points(as_card_list(translated)[1:7]))
  d <- deck(cards=list(card("A","Spades")),optional_cards=list(card("Joker","Joker")),include_optional=TRUE)
  translated <- translate_deck(d,"es")
  expect_identical(attr(translated,"main_cards"),as_card_list(translated)[1])
  expect_identical(attr(translated,"optional_cards"),as_card_list(translated)[2])
  expect_length(translate_deck(deck(),"es"),0)
  expect_error(translate_deck(deck(),"fr"),"en and es")
})
